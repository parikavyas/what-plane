export interface AirlineFlight {
  code: string; // ICAO operator code, e.g. DAL
  number: string; // flight number part, e.g. 123 or 12A
  name: string | null; // airline name when we know it
}

/**
 * Split an airline-style callsign (three letters then a number) into its parts.
 * Returns null for registrations and other callsigns that aren't airline flights.
 */
export function parseCallsign(callsign: string | null): AirlineFlight | null {
  const m = callsign?.trim().toUpperCase().match(/^([A-Z]{3})(\d[A-Z0-9]{0,4})$/);
  if (!m) return null;
  return { code: m[1], number: m[2], name: AIRLINES[m[1]] ?? null };
}
